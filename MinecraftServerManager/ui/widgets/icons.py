def _device_pixel_ratio() -> float:
    screen = QGuiApplication.primaryScreen()
    return screen.devicePixelRatio() if screen is not None else 1.0


def svg_pixmap(name: str, size: int = 16, color: str = "#94a3b8") -> QPixmap:
    if isinstance(size, str):  # compatibilidad con llamadas (nombre, color, tamaño)
        size, color = (color if isinstance(color, int) else 16), size

    inner = SVG_PATHS.get(name)
    if inner is None:
        log.warning("Icono desconocido: %s", name)
        inner = SVG_PATHS["alert"]

    svg_xml = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round">'
        f'{inner}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg_xml.encode("utf-8")))
    dpr = _device_pixel_ratio()
    px_size = round(size * dpr)
    pixmap = QPixmap(px_size, px_size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, px_size, px_size))
    painter.end()

    pixmap.setDevicePixelRatio(dpr)
    return pixmap


def svg_icon(name: str, size: int = 16, color: str = "#94a3b8") -> QIcon:
    return QIcon(svg_pixmap(name, size, color))


